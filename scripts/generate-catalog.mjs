#!/usr/bin/env node
// Generate every derived catalogue file from scripts/catalog-data.json plus
// the skill directories on disk:
//   plugins/<pack>/.claude-plugin/plugin.json   per-pack plugin manifest
//   plugins/<pack>/README.md                   per-pack readme
//   .claude-plugin/marketplace.json            the ccmaf-skills marketplace
//   .claude-plugin/plugin.json                 the all-in-one plugin
//   SKILLS.md                                  the full catalogue
//   skills-manifest.json                       machine-readable catalogue
//
// Usage: node scripts/generate-catalog.mjs [--check]
//   --check  write nothing; exit 1 if any generated file would change (CI).
//
// Skill directories (or pack directories) on disk that are not yet in
// catalog-data.json are "pending": they are left out of every generated file
// and reported. validate-skills.mjs --strict turns pending entries into errors.
import fs from 'node:fs';
import path from 'node:path';
import {
  ROOT, loadCatalog, diskPacks, diskSkills, countReferenceDocs, orderedPacks,
} from './lib.mjs';

const CHECK = process.argv.includes('--check');
const GENERATED_MD = '<!-- GENERATED by scripts/generate-catalog.mjs from scripts/catalog-data.json — do not edit by hand. -->';

const catalog = loadCatalog();
const mp = catalog.marketplace;
const author = { name: mp.owner };
const onDisk = new Set(diskPacks());
const notes = [];

// Resolve packs: catalogued AND on disk, in catalogue order.
const packs = [];
for (const p of orderedPacks(catalog)) {
  if (!onDisk.has(p.id)) {
    notes.push(`pack ${p.id} is in catalog-data.json but has no plugins/${p.id}/skills/ — skipped`);
    continue;
  }
  const skills = [];
  for (const s of diskSkills(p.id)) {
    const entry = catalog.skills[s];
    if (!entry) { notes.push(`pending skill ${p.id}/${s} (not in catalog-data.json) — left out`); continue; }
    if (entry.pack !== p.id) { notes.push(`skill ${s} is on disk in ${p.id} but catalogued under ${entry.pack} — left out`); continue; }
    skills.push({ id: s, summary: entry.summary, refs: countReferenceDocs(p.id, s) });
  }
  packs.push({ ...p, skills });
}
const catalogued = new Set(catalog.packs.map((p) => p.id));
for (const d of onDisk) if (!catalogued.has(d)) notes.push(`pending pack ${d} (not in catalog-data.json) — left out`);

const allSkills = packs.flatMap((p) => p.skills.map((s) => ({ ...s, pack: p.id })));
const total = allSkills.length;
const plural = (n, w) => `${n} ${w}${n === 1 ? '' : 's'}`;
const installCmd = (id) => `/plugin install ${id}@${mp.name}`;

// ---------- builders ----------
const json = (obj) => `${JSON.stringify(obj, null, 2)}\n`;

function packPluginJson(p) {
  return json({
    name: p.id,
    description: `CCMAF Skills — ${p.title}: ${p.description} (${plural(p.skills.length, 'skill')})`,
    author,
    homepage: mp.homepage,
    repository: mp.repository,
    license: mp.license,
    keywords: ['skills', 'agent-skills', 'ccmaf', p.id.replace(/^ccmaf-skills-/, '')],
    skills: p.skills.map((s) => `./skills/${s.id}`),
  });
}

function packReadme(p) {
  const rows = p.skills.map((s) => `| [\`${s.id}\`](skills/${s.id}/SKILL.md) | ${s.summary} | ${s.refs} |`);
  return [
    GENERATED_MD,
    '',
    `# CCMAF Skills — ${p.title} (\`${p.id}\`)`,
    '',
    p.description,
    '',
    `**Audience:** ${p.audience}`,
    '',
    '## Install',
    '',
    '```',
    `/plugin marketplace add drushegh/CCMAF---Skills`,
    installCmd(p.id),
    '```',
    '',
    p.id === 'ccmaf-skills-core' ? 'Core is the base pack: every other pack assumes it is installed.' : `Install \`ccmaf-skills-core\` alongside this pack.`,
    '',
    `## Skills (${p.skills.length})`,
    '',
    '| Skill | What it covers | Reference docs |',
    '|---|---|---|',
    ...rows,
    '',
    `The full catalogue across every pack is in [SKILLS.md](../../SKILLS.md).`,
    '',
  ].join('\n');
}

function marketplaceJson() {
  return json({
    $schema: 'https://anthropic.com/claude-code/marketplace.schema.json',
    name: mp.name,
    description: mp.description,
    owner: author,
    plugins: [
      {
        name: catalog.allInOne.name,
        source: './',
        description: `All ${total} CCMAF skills as one plugin. ${catalog.allInOne.description}`,
        category: 'development',
        keywords: ['skills', 'engineering-standards', 'agent-skills', 'best-practices'],
      },
      ...packs.map((p) => ({
        name: p.id,
        source: `./plugins/${p.id}`,
        description: `${p.title} — ${p.description} [${p.audience}] (${plural(p.skills.length, 'skill')})`,
        category: 'development',
        keywords: ['skills', 'agent-skills', 'ccmaf', p.id.replace(/^ccmaf-skills-/, '')],
      })),
    ],
  });
}

function rootPluginJson() {
  return json({
    name: catalog.allInOne.name,
    description: `All ${total} CCMAF skills in one plugin — the conventions, decision frameworks, pitfalls and verification rules a senior practitioner enforces, packaged so an agent behaves like a disciplined specialist. The same skills are also published as ${packs.length} role packs (ccmaf-skills-<pack>).`,
    author,
    homepage: mp.homepage,
    repository: mp.repository,
    license: mp.license,
    keywords: ['skills', 'engineering-standards', 'agent-skills', 'best-practices'],
    skills: allSkills.map((s) => `./plugins/${s.pack}/skills/${s.id}`).sort(),
  });
}

function skillsManifest() {
  return json({
    name: mp.name,
    title: 'CCMAF Skills — skill catalogue',
    repository: mp.repository,
    skillCount: total,
    packCount: packs.length,
    allInOne: { name: catalog.allInOne.name, install: installCmd(catalog.allInOne.name) },
    packs: packs.map((p) => ({
      id: p.id,
      title: p.title,
      audience: p.audience,
      description: p.description,
      install: installCmd(p.id),
      skills: p.skills.map((s) => ({
        id: s.id,
        summary: s.summary,
        path: `plugins/${p.id}/skills/${s.id}`,
        referenceDocs: s.refs,
      })),
    })),
  });
}

function anchor(text) {
  return text.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-');
}

function skillsMd() {
  const byId = Object.fromEntries(packs.map((p) => [p.id, p]));
  const roleRows = (catalog.roles || []).map((r) => {
    const list = r.packs.filter((id) => byId[id]).map((id) => `\`${id}\``).join(' + ');
    return `| ${r.role} | ${list} |`;
  });
  const packRows = packs.map((p) => `| [${p.title}](#${anchor(`${p.title} ${p.id}`)}) | \`${p.id}\` | ${p.skills.length} | ${p.audience} |`);
  const sections = packs.flatMap((p) => [
    `## ${p.title} (\`${p.id}\`)`,
    '',
    p.description,
    '',
    `**Audience:** ${p.audience} · **Install:** \`${installCmd(p.id)}\` · [Pack README](plugins/${p.id}/README.md)`,
    '',
    '| Skill | What it covers | Reference docs |',
    '|---|---|---|',
    ...p.skills.map((s) => `| [\`${s.id}\`](plugins/${p.id}/skills/${s.id}/SKILL.md) | ${s.summary} | ${s.refs} |`),
    '',
  ]);
  return [
    GENERATED_MD,
    '',
    '# CCMAF Skills — catalogue',
    '',
    `**${total} skills** in **${packs.length} packs**. Each skill is a self-contained directory: a lean \`SKILL.md\` plus on-demand reference docs.`,
    '',
    '## Install',
    '',
    '```',
    '/plugin marketplace add drushegh/CCMAF---Skills',
    `${installCmd('ccmaf-skills-core')}        # everyone`,
    `${installCmd('ccmaf-skills-engineering')} # every developer`,
    `${installCmd('ccmaf-skills-<pack>')}      # the packs your work needs`,
    '```',
    '',
    `Or install everything at once with \`${installCmd(catalog.allInOne.name)}\` (all ${total} skills; a larger skill listing in every session).`,
    '',
    '## Which packs do I need?',
    '',
    '| If you are… | Install |',
    '|---|---|',
    ...roleRows,
    '',
    '## Packs',
    '',
    '| Pack | Plugin | Skills | Audience |',
    '|---|---|---|---|',
    ...packRows,
    '',
    ...sections,
  ].join('\n');
}

// ---------- write / check ----------
const outputs = new Map();
for (const p of packs) {
  outputs.set(path.join('plugins', p.id, '.claude-plugin', 'plugin.json'), packPluginJson(p));
  outputs.set(path.join('plugins', p.id, 'README.md'), packReadme(p));
}
outputs.set(path.join('.claude-plugin', 'marketplace.json'), marketplaceJson());
outputs.set(path.join('.claude-plugin', 'plugin.json'), rootPluginJson());
outputs.set('SKILLS.md', skillsMd());
outputs.set('skills-manifest.json', skillsManifest());

for (const n of notes) console.log(`note: ${n}`);

const changed = [];
for (const [rel, content] of outputs) {
  const abs = path.join(ROOT, rel);
  const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
  if (current === content) continue;
  changed.push(rel.split(path.sep).join('/'));
  if (!CHECK) {
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }
}

if (CHECK) {
  if (changed.length) {
    console.error(`generate-catalog --check: ${changed.length} file(s) out of date — run node scripts/generate-catalog.mjs:`);
    for (const c of changed) console.error(`  ${c}`);
    process.exit(1);
  }
  console.log(`generate-catalog --check: all ${outputs.size} generated files up to date (${total} skills, ${packs.length} packs).`);
} else {
  console.log(`generate-catalog: ${total} skills, ${packs.length} packs; ${changed.length} of ${outputs.size} files written.`);
  for (const c of changed) console.log(`  wrote ${c}`);
}
